// Builds the ops page script: apps/web/dashboard/src/ops-view/*.ts inlined into one IIFE.
// The page CSP allows one hash-pinned inline script and no 'self' scripts, so the modules are joined:
// types stripped, imports and `export` dropped, `boot(window)` called. The output is committed
// (apps/web/dashboard/src/ops-view.gen.js) so every entry point that imports the server works without a
// build; the Docker build regenerates it and build-ops-view.test.ts fails when it is stale.
// Run: pnpm --filter @eyes/web-dashboard build
import { readFileSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";

const dir = new URL("../apps/web/dashboard/src/", import.meta.url);
export const OUT = new URL("ops-view.gen.js", dir);
const MODULES = ["format.ts", "table.ts", "overview.ts", "logs.ts", "actions.ts", "page.ts"];

export function buildOpsScript() {
  const code = MODULES.map((file) =>
    stripTypeScriptTypes(readFileSync(new URL(`ops-view/${file}`, dir), "utf8")),
  )
    .join("\n")
    .replace(/^import [^;]*;/gm, "")
    .replace(/^export /gm, "");
  return `// Generated by scripts/build-ops-view.ts from ops-view/*.ts. Do not edit.\n(() => {\n${code}\nboot(window);\n})();\n`;
}

if (import.meta.main) writeFileSync(OUT, buildOpsScript());

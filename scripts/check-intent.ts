import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { matchesGlob } from "node:path";
import { isDeepStrictEqual } from "node:util";

const GOVERNED = /^(apps|packages|cli|scripts|db)\//;
const CONTRACT = /^(packages\/core\/src\/|packages\/db\/migrations\/)/;
const EMPTY_TREE = "4b825dc642cb6eb9a060e54bf8d69288fbee4904";
const INDEX_PATH = "intent/INDEX.md";
const MANIFEST = /(^|\/)package\.json$/;
const DEPENDENCY_FILE =
  /(^|\/)(package\.json|pnpm-lock\.yaml|package-lock\.json|npm-shrinkwrap\.json|yarn\.lock|bun\.lockb?)$/;

type Intent = { path: string; task: string; files: string[]; why: string; verification: string };

const git = (...args: string[]) =>
  execFileSync("git", args, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
const lines = (s: string) => s.split("\n").filter(Boolean);

function resolveBase(): string {
  const wanted = process.env.INTENT_BASE || "origin/main";
  if (/^0+$/.test(wanted)) return EMPTY_TREE;
  try {
    return git("merge-base", wanted, "HEAD");
  } catch {
    return EMPTY_TREE;
  }
}

function changedFiles(base: string): Map<string, string> {
  const status = new Map<string, string>();
  for (const row of lines(git("diff", "--name-status", "--no-renames", base))) {
    const [code, file] = row.split("\t");
    if (code && file) status.set(file, code[0] ?? "M");
  }
  for (const file of lines(git("ls-files", "--others", "--exclude-standard"))) status.set(file, "A");
  return status;
}

function manifestWithoutVersions(text: string) {
  const manifest = JSON.parse(text);
  const versionPattern = /^[~^]?\d+\.\d+\.\d+(?:-[\da-zA-Z.-]+)?(?:\+[\da-zA-Z.-]+)?$/;
  for (const field of ["dependencies", "devDependencies", "peerDependencies", "optionalDependencies"]) {
    if (!(field in manifest)) continue;
    const versions = manifest[field];
    if (!versions || typeof versions !== "object" || Array.isArray(versions))
      throw new TypeError("Invalid dependency map");
    for (const [name, version] of Object.entries(versions)) {
      if (typeof version !== "string") throw new TypeError("Invalid dependency version");
      if (versionPattern.test(version)) versions[name] = null;
    }
  }
  return manifest;
}

function dependencyVersionsOnly(base: string, changed: Map<string, string>): boolean {
  for (const [file, status] of changed) {
    if (status !== "M" || !DEPENDENCY_FILE.test(file)) return false;
    if (!MANIFEST.test(file)) continue;
    try {
      const before = manifestWithoutVersions(git("show", `${base}:${file}`));
      const after = manifestWithoutVersions(readFileSync(file, "utf8"));
      if (!isDeepStrictEqual(before, after)) return false;
    } catch {
      return false;
    }
  }
  return changed.size > 0;
}

function parseIntent(path: string): Intent {
  const text = readFileSync(path, "utf8");
  const front = text.match(/^---\n([\s\S]*?)\n---/)?.[1] ?? "";
  const field = (name: string) => front.match(new RegExp(`^${name}:\\s*(.*)$`, "m"))?.[1]?.trim() ?? "";
  const inline = field("files");
  const files = inline.startsWith("[")
    ? inline.slice(1, -1).split(",")
    : [...(front.split(/^files:.*$/m)[1] ?? "").matchAll(/^\s+-\s+(.+)$/gm)].map((m) => m[1] ?? "");
  const section = (name: string) =>
    text
      .split(/^## /m)
      .find((s) => s.startsWith(name))
      ?.slice(name.length)
      .trim() ?? "";
  return {
    path,
    task: field("task"),
    files: files.map((f) => f.trim().replace(/^["']|["']$/g, "")).filter(Boolean),
    why: section("Why"),
    verification: section("Verification"),
  };
}

function intentFiles(): string[] {
  return readdirSync("intent")
    .filter((f) => f.endsWith(".md") && f !== "INDEX.md")
    .map((f) => `intent/${f}`);
}

const covers = (intent: Intent, file: string) =>
  intent.files.some((pattern) => file === pattern || matchesGlob(file, pattern));

function renderIndex(intents: Intent[]): string {
  const tracked = lines(git("ls-files", "--cached", "--others", "--exclude-standard"))
    .filter((f) => GOVERNED.test(f) && existsSync(f))
    .sort();
  const rows = tracked.map((file) => {
    const owners = intents.filter((i) => covers(i, file)).map((i) => `[${i.task}](${i.path.slice(7)})`);
    return `| ${file} | ${owners.join(", ") || "none"} |`;
  });
  return [
    "# Intent index",
    "",
    "Generated by `pnpm intent:index`. Do not edit by hand.",
    "",
    "| File | Intent |",
    "|---|---|",
    ...rows,
    "",
  ].join("\n");
}

const intents = intentFiles().map(parseIntent);
const index = renderIndex(intents);

if (process.argv.includes("--write-index")) {
  writeFileSync(INDEX_PATH, index);
  console.log(`wrote ${INDEX_PATH}`);
  process.exit(0);
}

const errors: string[] = [];
const base = resolveBase();
const changed = changedFiles(base);
const dependencyOnly = dependencyVersionsOnly(base, changed);
const changedIntents = intents.filter((i) => changed.has(i.path));

for (const intent of changedIntents) {
  if (!intent.task) errors.push(`${intent.path}: frontmatter is missing "task"`);
  if (intent.files.length === 0) errors.push(`${intent.path}: frontmatter "files" is empty`);
  if (!intent.why) errors.push(`${intent.path}: "## Why" section is empty`);
  if (!intent.verification) errors.push(`${intent.path}: "## Verification" section is empty`);
}

for (const file of changed.keys()) {
  if (dependencyOnly || !GOVERNED.test(file)) continue;
  if (!changedIntents.some((i) => covers(i, file))) {
    errors.push(`${file}: changed but no intent file changed in this diff lists it under "files"`);
  }
}

const contractEdits = [...changed].filter(([file, code]) => CONTRACT.test(file) && code !== "A");
const adrChanged = [...changed.keys()].some((f) => f.startsWith("intent/decisions/"));
if (contractEdits.length > 0 && !adrChanged) {
  errors.push(
    `contract files modified (${contractEdits.map(([f]) => f).join(", ")}) without an ADR in intent/decisions/`,
  );
}

const committed = existsSync(INDEX_PATH) ? readFileSync(INDEX_PATH, "utf8") : "";
if (committed !== index)
  errors.push(`${INDEX_PATH} is stale: run \`pnpm intent:index\` and commit the result`);

if (errors.length > 0) {
  console.error(`intent check failed (${errors.length}):\n${errors.map((e) => `  - ${e}`).join("\n")}`);
  process.exit(1);
}
console.log(`intent check ok: ${changed.size} changed files, ${changedIntents.length} intent files`);
